"""
CIF to Quantum ESPRESSO Wannier90 input generator.

This module provides functionality to generate Quantum ESPRESSO and Wannier90
input files from CIF (Crystallographic Information File) structures. It supports
both standard DFT calculations and advanced features like spin-orbit coupling
and magnetic calculations.

Usage:
    cif2qewan.py <cif_file> <toml_file> [--so] [--mag]

Options:
    --so     input including spin-orbit couplings
    --mag    ferromagnetic calculations

Author: Generated by cif2qewan
"""

