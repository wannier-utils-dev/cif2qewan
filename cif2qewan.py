class pseudo_list:
    """
    Handle pseudopotential information and selection.
    
    This class manages pseudopotential files and their associated parameters
    for Quantum ESPRESSO calculations. It reads pseudopotential information
    from a CSV file and provides methods to retrieve pseudopotential data.
    
    Parameters
    ----------
    pseudo_dir : str
        Directory containing pseudopotential files.
    pp_list_path : str
        Path to CSV file containing pseudopotential information.
        
    Attributes
    ----------
    pseudo_dir : str
        Directory containing pseudopotential files.
    pp_info : dict
        Dictionary mapping atom types to pseudopotential information.
    """
    
    def __init__(self, pseudo_dir: str, pp_list_path: str) -> None:
        """
        Initialize pseudopotential list handler.
        
        Parameters
        ----------
        pseudo_dir : str
            Directory containing pseudopotential files.
        pp_list_path : str
            Path to CSV file containing pseudopotential information.
        """
        self.pseudo_dir = pseudo_dir
        self.pp_info = self.read_pp_info(pp_list_path)

    def pseudo(self, atm: str) -> tuple:
        """
        Get pseudopotential information for an atom type.
        
        Parameters
        ----------
        atm : str
            Atom type symbol.
            
        Returns
        -------
        tuple
            Pseudopotential information tuple containing:
            - pp_file_name: Name of pseudopotential file
            - nexclude: Number of excluded bands
            - orbital: Orbital types for projections
            - num_wann: Number of Wannier functions
            - ecutwfc: Wavefunction cutoff energy
            - ecutrho: Charge density cutoff energy
        """
        return self.pp_info[atm]

    def read_pp_info(self, pp_list_path: str) -> dict:
        """
        Read pseudopotential information from CSV file.
        
        Parameters
        ----------
        pp_list_path : str
            Path to CSV file containing pseudopotential information.
            
        Returns
        -------
        dict
            Dictionary mapping atom types to pseudopotential information.
        """
        csv_input = pd.read_csv(pp_list_path, sep=",").fillna("NaN")
        pp_dict = {}
        
        for value in csv_input.values:
            if value[1] == "NaN":  # No pseudopotential file
                pp_dict[value[0]] = None
            else:
                # Handle missing values
                if value[2] == "NaN":  # nexclude
                    value[2] = 0
                if value[3] == "NaN":  # orbital
                    value[3] = ""
                if value[4] == "NaN":  # ecutwfc
                    value[4] = 0
                if value[5] == "NaN":  # ecutrho
                    value[5] = 0

                # Create pseudopotential filename
                pp_file_name = f"{value[1]}.UPF"
                
                # Calculate number of Wannier functions from orbital types
                num_wann = 0
                for s in value[3]:
                    if s == "s":
                        num_wann += 1
                    elif s == "p":
                        num_wann += 3
                    elif s == "d":
                        num_wann += 5
                    elif s == "f":
                        num_wann += 7
                        
                # Store pseudopotential information
                pp_dict[value[0]] = (pp_file_name, int(value[2]), value[3], 
                                   num_wann, float(value[4]), float(value[5]))
        return pp_dict


