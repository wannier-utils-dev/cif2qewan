class Hamiltonian:
    """
    Wannier90 Hamiltonian data handler.

    This class contains the information of Hamiltonian generated by wannier90 code.
    All units are eV and A. It reads the hr.dat file and provides methods for
    diagonalizing the Hamiltonian at arbitrary k-points.

    Attributes
    ----------
    num_wann : int
        Number of Wannier orbitals.
    nrpts : int
        Number of R vectors in the Wigner-Seitz grid.
    ndegen : np.ndarray
        Degeneracies of Wigner-Seitz grid points (shape: [nrpts]).
    irvec : np.ndarray
        Lattice vectors for unit cells (shape: [3, nrpts]).
    ir0 : int
        Index of H(R=0). Returns -1 if not found.
    ham_r : np.ndarray
        Wannier-based Hamiltonian (shape: [num_wann, num_wann, nrpts]).
    reorder : bool
        Whether to reorder indices of Wannier orbitals.

    Examples
    --------
    >>> h = Hamiltonian("pwscf_hr.dat")
    >>> ek, v = h.diagonalize([0.0, 0.0, 0.0])
    """

    def __init__(self, file_hr: str, reorder: bool = False) -> None:
        """
        Initialize Hamiltonian from hr.dat file.

        Parameters
        ----------
        file_hr : str
            Path to the hr.dat file generated by Wannier90.
        reorder : bool, optional
            Whether to reorder indices of Wannier orbitals in dat file.
            Used for compatibility with VASP and older Wannier90 versions.
            Default is False.

        Examples
        --------
        >>> h = Hamiltonian("pwscf_hr.dat")
        >>> h_reordered = Hamiltonian("pwscf_hr.dat", reorder=True)
        """
        self.reorder = reorder
        self._read_hr(file_hr)
        self._ws_vectors = None
        self._ws_matrices = None

    def load_wsvec(self, file_wsvec: str) -> None:
        """Use Wannier90's pair-dependent WS shifts when interpolating bands.

        ``hr.dat`` stores one R for each matrix element, while ``wsvec.dat``
        specifies the Born-von-Karman equivalent R vectors selected for each
        pair of Wannier functions.  Equal-distance choices share the weight.
        """
        try:
            with open(file_wsvec) as stream:
                header = stream.readline().lower()
                if "write_ndegen_applied=.true." in header:
                    raise ValueError("write_ndegen_applied output is not supported")
                if "use_ws_distance=.false." in header:
                    self._ws_vectors = None
                    self._ws_matrices = None
                    return
                if "use_ws_distance=.true." not in header:
                    raise ValueError("missing use_ws_distance header")

                matrices = {}
                for ir in range(self.nrpts):
                    r = self.irvec[:, ir]
                    for m in range(self.num_wann):
                        for n in range(self.num_wann):
                            record = [int(x) for x in stream.readline().split()]
                            if record != [*r, m + 1, n + 1]:
                                raise ValueError(
                                    f"WS record order differs at R={ir}, m={m}, n={n}"
                                )
                            count = int(stream.readline())
                            if count < 1:
                                raise ValueError(
                                    "WS shift multiplicity must be positive"
                                )
                            amplitude = self.ham_r[m, n, ir] / (self.ndegen[ir] * count)
                            for _ in range(count):
                                shift = [int(x) for x in stream.readline().split()]
                                if len(shift) != 3:
                                    raise ValueError(
                                        "WS shift must have three components"
                                    )
                                key = tuple(int(x) for x in r + shift)
                                if key not in matrices:
                                    matrices[key] = np.zeros(
                                        (self.num_wann, self.num_wann), dtype=complex
                                    )
                                matrices[key][m, n] += amplitude
                if stream.read().strip():
                    raise ValueError("unread WS records remain")
            self._ws_vectors = np.array(list(matrices), dtype=np.int64)
            self._ws_matrices = np.stack(list(matrices.values()))
        except (OSError, ValueError, IndexError, TypeError) as exc:
            raise DataFileError(
                f"cannot read the Wannier90 WS vectors {file_wsvec}: {exc}"
            ) from exc

    def _read_hr(self, file_hr: str) -> None:
        """
        Read Hamiltonian data from hr.dat file.

        This method parses the Wannier90 hr.dat file format and loads
        the Hamiltonian matrix elements and lattice vectors.

        Parameters
        ----------
        file_hr : str
            Path to the hr.dat file.

        Raises
        ------
        Exception
            If the file cannot be read or parsed.
        """
        try:
            # Check if file exists
            if os.path.exists(file_hr):
                fp = open(file_hr, "r")
            else:
                raise FileNotFoundError(f"File {file_hr} not found")

            # Skip empty line
            fp.readline()

            # Read number of Wannier orbitals and R points
            self.num_wann = int(fp.readline())
            self.nrpts = int(fp.readline())

            # Read degeneracies (15 per line)
            ndegen = []
            for i in range(int(self.nrpts / 15) + 1):
                ndegen += [int(x) for x in fp.readline().split()]
                if len(ndegen) >= self.nrpts:
                    break
            self.ndegen = np.array(ndegen)

            # Initialize Hamiltonian and lattice vectors
            self.ham_r = np.zeros(
                (self.num_wann, self.num_wann, self.nrpts), dtype=np.complex128
            )
            self.irvec = np.zeros((3, self.nrpts), dtype=np.int64)

            # Find R=0 index
            self.ir0 = -1

            # Read Hamiltonian matrix elements
            for i, m, n in itertools.product(
                range(self.nrpts), range(self.num_wann), range(self.num_wann)
            ):
                irx, iry, irz, _, _, tr, ti = fp.readline().split()

                # Store lattice vectors (only once per R point)
                if m == 0 and n == 0:
                    self.irvec[0:3, i] = np.array([int(x) for x in [irx, iry, irz]])
                    if np.all(self.irvec[0:3, i] == 0):
                        self.ir0 = i

                # Store Hamiltonian matrix elements
                if self.reorder:
                    # VASP, wannier ver1. etc - reorder indices
                    mr = m // 2 + (self.num_wann // 2) * (m % 2)
                    nr = n // 2 + (self.num_wann // 2) * (n % 2)
                    self.ham_r[nr, mr, i] = float(tr) + float(ti) * 1j
                else:
                    # Normal order
                    self.ham_r[n, m, i] = float(tr) + float(ti) * 1j

            fp.close()

        except (OSError, ValueError, IndexError) as e:
            raise DataFileError(
                f"cannot read the Wannier90 Hamiltonian {file_hr}: {e}"
            ) from e

    def diagonalize(self, k: np.ndarray) -> Tuple[np.ndarray, np.ndarray]:
        """
        Diagonalize the Hamiltonian at a given k-point.

        This method constructs the k-space Hamiltonian H(k) from the
        real-space Hamiltonian H(R) using the Fourier transform:
        H(k) = Σ_R H(R) * exp(i*k·R) / deg(R)

        Parameters
        ----------
        k : np.ndarray
            K-point in crystal coordinates (shape: [3]).

        Returns
        -------
        tuple[np.ndarray, np.ndarray]
            A tuple containing:
            - e: Eigenvalues (energies) in eV
            - v: Eigenvectors (wavefunctions)

        Examples
        --------
        >>> h = Hamiltonian("pwscf_hr.dat")
        >>> ek, v = h.diagonalize([0.0, 0.0, 0.0])
        >>> print(f"Energies: {ek}")
        """
        if self._ws_vectors is None:
            # Standard interpolation without pair-dependent WS shifts.
            factor = np.exp(2j * np.pi * np.dot(k, self.irvec)) / self.ndegen
            ham = np.dot(self.ham_r, factor)
        else:
            factor = np.exp(2j * np.pi * np.dot(self._ws_vectors, k))
            ham = np.einsum("r,rmn->mn", factor, self._ws_matrices, optimize=True)

        # Diagonalize to get eigenvalues and eigenvectors
        e, v = np.linalg.eigh(ham)

        return (e, v)


class Nscfout:
    """
    Quantum ESPRESSO NSCF output parser.

    This class parses the output from Quantum ESPRESSO NSCF calculations
    to extract k-points, energies, and other relevant information.
    The NSCF calculation must be done with "verbosity = 'high'" for
    proper parsing of the output.

    Attributes
    ----------
    ef : float
        Fermi energy in eV.
    nbnd : int
        Number of Kohn-Sham bands.
    nk : int
        Number of k-points.
    kp_cart : np.ndarray
        K-points in Cartesian coordinates (shape: [nk, 3]).
    kp_cryst : np.ndarray
        K-points in crystal coordinates (shape: [nk, 3]).
    wk : np.ndarray
        K-point weights (shape: [nk]).
    energy : np.ndarray
        Band energies (shape: [nk, nbnd]).

    Examples
    --------
    >>> nscf_data = Nscfout("nscf.out")
    >>> print(f"Fermi energy: {nscf_data.ef} eV")
    """

    def __init__(self, nscf_out: str) -> None:
        """
        Parse NSCF output file.

        Parameters
        ----------
        nscf_out : str
            Path to the NSCF output file.
        """
        with open(nscf_out, "r") as fp:
            lines = fp.readlines()

        # Parse header information
        for i, line in enumerate(lines):
            if "the Fermi energy" in line:
                self.ef = float(line[26:35])
            if "number of Kohn-Sham" in line:
                self.nbnd = int(line[35:])
            if "number of k points=" in line:
                self.nk = int(line[25:31])
                # Initialize k-point arrays
                self.kp_cart = np.zeros([self.nk, 3])
                self.kp_cryst = np.zeros([self.nk, 3])
                self.wk = np.zeros([self.nk])

                # Parse k-points
                for j in range(self.nk):
                    self.kp_cart[j] = np.array(
                        [float(x) for x in lines[i + j + 2][20:56].split()]
                    )
                    self.wk[j] = float(lines[i + j + 2][65:])
                    self.kp_cryst[j] = np.array(
                        [float(x) for x in lines[i + j + 4 + self.nk][20:56].split()]
                    )

        # Parse band energies
        self.energy = np.zeros([self.nk, self.nbnd])
        nline, nlinemod = divmod(self.nbnd, 8)
        if nlinemod > 0:
            nline += 1

        for j in range(self.nk):
            # Find k-point in output
            kp_str = "k =%7.4f%7.4f%7.4f" % tuple(self.kp_cart[j])
            for i, line in enumerate(lines):
                if kp_str in line:
                    # Parse energy values (8 per line)
                    tmp_list = "".join(lines[i + 2 : i + 2 + nline]).split()
                    ene_list = []

                    # Handle long energy values that may be concatenated
                    for l_tmp in tmp_list:
                        len_max = 8
                        if len(l_tmp) > len_max:
                            # Split concatenated values
                            for s in range(len(l_tmp) // (len_max + 1)):
                                ene_list.append(
                                    l_tmp[s * (len_max + 1) : (s + 1) * (len_max + 1)]
                                )
                        else:
                            ene_list.append(l_tmp)

                    # Store energies for this k-point
                    self.energy[j, :] = [float(x) for x in ene_list]


def get_nexclude(pwscf_win: str) -> int:
    """
    Extract number of excluded bands from Wannier90 input file.

    Parameters
    ----------
    pwscf_win : str
        Path to the Wannier90 input file (pwscf.win).

    Returns
    -------
    int
        Number of excluded bands.

    Examples
    --------
    >>> nexclude = get_nexclude("pwscf.win")
    >>> print(f"Excluded bands: {nexclude}")
    """
    nexclude = 0
    with open(pwscf_win, "r") as fp:
        for line in fp.readlines():
            if "exclude" in line:
                # Parse exclude_bands = 1-N format
                nexclude = int(line.split("-")[1])
                break
    return nexclude


def ws_distance_disabled(pwscf_win: str) -> bool:
    """Check whether the input explicitly requests legacy interpolation."""
    with open(pwscf_win) as stream:
        return any(
            re.match(r"^\s*use_ws_distance\s*=\s*\.false\.\s*(?:!.*)?$", line, re.I)
            for line in stream
        )


def main(argv=None) -> int:
    """
    Main function for wannier_conv command-line interface.

    This function provides the entry point for the wannier_conv command
    and handles the convergence checking workflow.
    """
    # Set up command-line argument parser
    parser = argparse.ArgumentParser(
        description="Check accuracy of Wannier90 interpolation",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  wannier_conv -e 5.0 -o ./output
  wannier_conv -e 0.0 -i ./check_wannier/nscf.out -o ./results
        """,
    )
    parser.add_argument(
        "-e",
        type=float,
        default=0.0,
        dest="emax",
        help="Maximum energy above Fermi level for comparison (eV)",
    )
    parser.add_argument(
        "-o",
        dest="odir",
        required=True,
        help="Output directory for convergence results",
    )
    parser.add_argument(
        "-i",
        default="./check_wannier/nscf.out",
        dest="nscf_file",
        help="Path to NSCF output file",
    )
    parser.add_argument(
        "--no-ws-distance",
        action="store_true",
        help="Use legacy interpolation without pwscf_wsvec.dat",
    )

    # Parse command-line arguments
    args = parser.parse_args(argv)
    try:
        # Set energy window for comparison
        emin = -200.0  # Minimum energy (well below Fermi level)
        emax = args.emax  # Maximum energy above Fermi level
        output_dir = args.odir
        nscf_file = args.nscf_file

        # Load data from files
        print("Loading NSCF data...")
        nscf_data = Nscfout(nscf_file)

        print("Loading Wannier90 Hamiltonian...")
        nexclude = get_nexclude("./pwscf.win")
        h = Hamiltonian("./pwscf_hr.dat")
        wsvec_file = "./pwscf_wsvec.dat"
        if not args.no_ws_distance:
            if os.path.exists(wsvec_file):
                h.load_wsvec(wsvec_file)
            elif not ws_distance_disabled("./pwscf.win"):
                raise DataFileError(
                    "pwscf_wsvec.dat is missing; cannot reproduce Wannier90's "
                    "default use_ws_distance interpolation"
                )

        print(f"Comparing energies in window [{emin:.2f}:{emax:.2f}] eV...")

        # Calculate energy differences between Wannier90 and DFT
        delta_sum = 0.0
        delta_max = 0.0
        nek = 0  # Number of k-points and bands compared

        for i in range(nscf_data.nk):
            # Get Wannier90 energies at this k-point
            ek, _ = h.diagonalize(nscf_data.kp_cryst[i])

            # Determine energy range for comparison
            nek_low = np.sum(ek - nscf_data.ef < emin)
            nek_max = np.sum(ek - nscf_data.ef < emax)

            # Ensure we don't exceed available bands
            if nexclude + nek_max > nscf_data.nbnd:
                nek_max = nscf_data.nbnd - nexclude

            # Skip if no bands in this energy range
            if nek_max == nek_low:
                continue

            # Count bands in comparison
            nek += nek_max - nek_low

            # Calculate energy differences (squared)
            ediff = (
                ek[nek_low:nek_max]
                - nscf_data.energy[i, nexclude + nek_low : nexclude + nek_max]
            ) ** 2
            delta_sum += np.sum(ediff)
            delta_max = max([delta_max, np.max(ediff)])

        # Write convergence results
        output_file = os.path.join(output_dir, f"CONV_{emax}")
        with open(output_file, "w") as fp:
            # Keep the CONV format unchanged: existing scripts parse these lines.
            fp.write(f"# energy window [{emin:>5.2f}:{emax:>5.2f}]\n")

            if nek > 0:
                avg_diff = np.sqrt(delta_sum / nek)
                fp.write(f"average diff = {avg_diff:>15.8f}\n")
            else:
                fp.write("average diff = NaN\n")

            max_diff = np.sqrt(delta_max)
            fp.write(f"max diff     = {max_diff:>15.8f}\n")

        print(f"Convergence results written to: {output_file}")
        if nek > 0:
            print(f"Average difference: {np.sqrt(delta_sum/nek):.6f} eV")
            print(f"Maximum difference: {np.sqrt(delta_max):.6f} eV")
        else:
            print("No bands found in the specified energy window")

    except (Cif2qewanError, OSError) as exc:
        print(f"wannier_conv: error: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
