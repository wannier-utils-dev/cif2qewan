class TestPackageInstallation(unittest.TestCase):
    """Test cases for package installation."""

    def test_package_import(self):
        """Test that the package can be imported."""
        try:
            import cif2qewan

            self.assertTrue(hasattr(cif2qewan, "__version__"))
            self.assertTrue(hasattr(cif2qewan, "__author__"))
            self.assertTrue(hasattr(cif2qewan, "__license__"))
        except ImportError as e:
            self.fail(f"cif2qewan package could not be imported: {e}")

    def test_command_line_scripts(self):
        """Test that command line scripts are available."""
        # Test that the scripts can be imported (excluding get_cif)
        scripts = ["cif2qewan", "band_comp", "wannier_conv"]

        for script in scripts:
            try:
                sys.path.insert(
                    0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
                )
                if script == "cif2qewan":
                    import cif2qewan

                    # cif2qewan.py doesn't have a main function, it runs directly
                    self.assertTrue(True)  # Just test that it can be imported
                elif script == "band_comp":
                    import band_comp

                    self.assertTrue(hasattr(band_comp, "main"))
                elif script == "wannier_conv":
                    import wannier_conv

                    # wannier_conv.py doesn't have a main function, it runs directly
                    self.assertTrue(True)  # Just test that it can be imported
            except ImportError as e:
                self.fail(f"Script {script} could not be imported: {e}")

    def test_package_metadata(self):
        """Test package metadata."""
        try:
            import cif2qewan

            # Test version
            self.assertIsNotNone(cif2qewan.__version__)
            self.assertIsInstance(cif2qewan.__version__, str)

            # Test author
            self.assertIsNotNone(cif2qewan.__author__)
            self.assertIsInstance(cif2qewan.__author__, str)

            # Test license
            self.assertIsNotNone(cif2qewan.__license__)
            self.assertIsInstance(cif2qewan.__license__, str)

        except ImportError as e:
            self.fail(f"Package metadata not available: {e}")


