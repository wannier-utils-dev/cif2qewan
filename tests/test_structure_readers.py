# cif2cell subprocess adapter
# --------------------------------------------------------------------------


def fake_cif2cell(tmp_path, behaviour):
    """A stand-in for cif2cell that records its arguments.

    behaviour: "ok" writes the Fe output to the -o path, "fail" exits 2 with
    a message, "silent" exits 0 without writing anything.
    """
    script = tmp_path / "fake_cif2cell.py"
    script.write_text(textwrap.dedent(f"""
            import pathlib, sys
            args = sys.argv[1:]
            pathlib.Path({str(tmp_path / "args.txt")!r}).write_text("\\n".join(args))
            pathlib.Path({str(tmp_path / "cwd.txt")!r}).write_text(str(pathlib.Path.cwd()))
            behaviour = {behaviour!r}
            if behaviour == "fail":
                sys.stderr.write("cif2cell: cannot parse CIF\\n")
                sys.exit(2)
            if behaviour == "ok":
                out = args[args.index("-o") + 1]
                pathlib.Path(out).write_text(pathlib.Path({str(FE / "cif_scf.in")!r}).read_text())
            """))
    launcher = tmp_path / "cif2cell"
    launcher.write_text(f'#!/bin/sh\nexec {sys.executable} {script} "$@"\n')
    launcher.chmod(launcher.stat().st_mode | stat.S_IEXEC)
    return launcher


def test_reader_runs_cif2cell_in_a_temporary_directory(tmp_path, monkeypatch):
    workdir = tmp_path / "work"
    workdir.mkdir()
    monkeypatch.chdir(workdir)
    cif = tmp_path / "Fe (test) ü.cif"
    cif.write_text((FE / "mp-13_Fe.cif").read_text())

    reader = Cif2cellReader(fake_cif2cell(tmp_path, "ok"), k_resolution=0.15)
    out = reader.run(cif)

    assert out.kmesh == (21, 21, 21)
    args = (tmp_path / "args.txt").read_text().splitlines()
    assert args[:4] == ["-p", "pwscf", "--setup-all", "--k-resolution=0.150"]
    assert "--print-digits=10" in args
    assert args[-1] == str(cif.resolve())  # passed as one argument, unescaped
    run_cwd = (tmp_path / "cwd.txt").read_text()
    assert run_cwd != str(workdir) and not os.path.exists(run_cwd)  # temp dir, cleaned
    assert not (
        workdir / "cif_scf.in"
    ).exists()  # nothing left in the working directory
    assert os.getcwd() == str(workdir)

    structure = reader.read(cif)
    assert structure == out.structure


def test_reader_reports_cif2cell_failures(tmp_path):
    cif = tmp_path / "x.cif"
    cif.write_text("data_x\n")

    with pytest.raises(ExternalCommandError) as info:
        Cif2cellReader(fake_cif2cell(tmp_path, "fail")).run(cif)
    assert info.value.returncode == 2
    assert "cannot parse CIF" in str(info.value)

    with pytest.raises(ExternalCommandError, match="wrote no cif_scf.in"):
        Cif2cellReader(fake_cif2cell(tmp_path, "silent")).run(cif)

    with pytest.raises(ExternalCommandError, match="cannot run cif2cell"):
        Cif2cellReader(tmp_path / "does_not_exist").run(cif)

    with pytest.raises(StructureError, match="CIF file not found"):
        Cif2cellReader(fake_cif2cell(tmp_path, "ok")).run(tmp_path / "missing.cif")


