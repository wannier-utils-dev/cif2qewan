pymatgen = pytest.importorskip("pymatgen")


def test_pymatgen_reader_primitive_and_conventional():
    primitive = PymatgenReader().read(FE / "mp-13_Fe.cif")
    assert primitive.num_sites == 1
    assert primitive.elements == ("Fe",)
    assert primitive.volume == pytest.approx(2.8630355**3 / 2.0)

    conventional = PymatgenReader(primitive=False).read(FE / "mp-13_Fe.cif")
    assert conventional.num_sites == 2
    assert conventional.volume == pytest.approx(2.8630355**3)
    assert not conventional.is_magnetic


def test_both_readers_agree_on_fe():
    """Step 3 completion criterion: physically equivalent structures."""
    from_cif2cell = Cif2cellReader.read_output(FE / "cif_scf.in").structure
    from_pymatgen = PymatgenReader().read(FE / "mp-13_Fe.cif")
    assert compare_structures(from_cif2cell, from_pymatgen) == []
    # but the conventional cell is not the same structure description
    conventional = PymatgenReader(primitive=False).read(FE / "mp-13_Fe.cif")
    assert not structures_equivalent(from_cif2cell, conventional)


def test_pymatgen_reader_errors(tmp_path):
    with pytest.raises(StructureError, match="not found"):
        PymatgenReader().read(tmp_path / "missing.cif")
    bad = tmp_path / "bad.cif"
    bad.write_text("this is not a cif\n")
    with pytest.raises(StructureError):
        PymatgenReader().read(bad)


def test_pymatgen_conversion_keeps_magmom_and_rejects_mixed_sites():
    from pymatgen.core import Lattice, Structure

    structure = Structure(
        Lattice.cubic(2.8),
        ["Fe", "Fe"],
        [[0, 0, 0], [0.5, 0.5, 0.5]],
        site_properties={"magmom": [[0, 0, 2.2], [0, 0, -2.2]]},
    )
    normalized = PymatgenReader.from_pymatgen(structure)
    assert normalized.is_magnetic
    assert normalized.sites[0].magmom.vector == pytest.approx((0.0, 0.0, 2.2))
    assert normalized.sites[1].magmom.vector == pytest.approx((0.0, 0.0, -2.2))

    collinear = Structure(
        Lattice.cubic(2.8), ["Fe"], [[0, 0, 0]], site_properties={"magmom": [2.2]}
    )
    assert PymatgenReader.from_pymatgen(collinear).sites[
        0
    ].magmom.vector == pytest.approx((0.0, 0.0, 2.2))

    mixed = Structure(Lattice.cubic(4.0), [{"Na": 0.5, "K": 0.5}], [[0, 0, 0]])
    with pytest.raises(StructureError, match="mixed occupancy"):
        PymatgenReader.from_pymatgen(mixed)

    partial = Structure(Lattice.cubic(4.0), [{"Na": 0.5}], [[0, 0, 0]])
    with pytest.raises(StructureError, match="partial occupancy"):
        PymatgenReader.from_pymatgen(partial)


# --------------------------------------------------------------------------
# structure comparison
# --------------------------------------------------------------------------

BCC = np.array([[-0.5, 0.5, 0.5], [0.5, -0.5, 0.5], [0.5, 0.5, -0.5]]) * ALAT
BCC_OTHER = np.array([[0.5, 0.5, 0.5], [0.5, -0.5, -0.5], [-0.5, 0.5, -0.5]]) * ALAT


def test_compare_accepts_other_primitive_vectors_and_translations():
    a = NormalizedStructure(BCC, (AtomicSite("Fe", (0, 0, 0)),))
    b = NormalizedStructure(BCC_OTHER, (AtomicSite("Fe", (1.0, -2.0, 3.0)),))
    assert compare_structures(a, b) == []

    nacl_a = NormalizedStructure(
        np.eye(3) * 4.0,
        (AtomicSite("Na", (0, 0, 0)), AtomicSite("Cl", (0.5, 0.5, 0.5))),
    )
    nacl_b = NormalizedStructure(
        np.eye(3) * 4.0,
        (AtomicSite("Cl", (-0.5, 0.5, 1.5)), AtomicSite("Na", (1.0, 0.0, 0.0))),
    )
    assert structures_equivalent(nacl_a, nacl_b)  # sites reordered and translated
    shifted_origin = NormalizedStructure(
        np.eye(3) * 4.0,
        (AtomicSite("Na", (0.25, 0.25, 0.25)), AtomicSite("Cl", (0.75, 0.75, 0.75))),
    )
    assert not structures_equivalent(
        nacl_a, shifted_origin
    )  # same crystal, other frame


def test_compare_reports_differences():
    a = NormalizedStructure(BCC, (AtomicSite("Fe", (0, 0, 0)),))
    supercell = NormalizedStructure(
        np.eye(3) * ALAT,
        (AtomicSite("Fe", (0, 0, 0)), AtomicSite("Fe", (0.5, 0.5, 0.5))),
    )
    (difference,) = compare_structures(a, supercell)
    assert difference.startswith("volumes differ: 11.734167 vs 23.4683")

    rotated = NormalizedStructure(BCC[[1, 2, 0]] * np.array([1, 1, 1.0001]), a.sites)
    assert compare_structures(a, rotated)[0].startswith("volumes differ")

    other_element = NormalizedStructure(BCC, (AtomicSite("Co", (0, 0, 0)),))
    assert compare_structures(a, other_element) == [
        "no counterpart for Co at (0.0, 0.0, 0.0)"
    ]

    moved = NormalizedStructure(BCC, (AtomicSite("Fe", (0.1, 0, 0)),))
    assert len(compare_structures(a, moved)) == 1

    up = NormalizedStructure(
        BCC, (AtomicSite("Fe", (0, 0, 0), MagneticMoment((0, 0, 2.2))),)
    )
    down = NormalizedStructure(
        BCC, (AtomicSite("Fe", (0, 0, 0), MagneticMoment((0, 0, -2.2))),)
    )
    assert not structures_equivalent(up, down)
    assert not structures_equivalent(up, a)
    assert structures_equivalent(
        a, a.with_sites([AtomicSite("Fe", (0, 0, 0), MagneticMoment.zero())])
    )
