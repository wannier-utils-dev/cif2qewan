"""Tests for the structure readers.

The cif2cell adapter is exercised with a fake ``cif2cell`` script, so that
neither cif2cell nor a network connection is needed.
``test_both_readers_agree_on_fe`` checks that the pymatgen reader and the
cif2cell output describe the same crystal within tolerance.
"""

import os
import stat
import sys
import textwrap

import numpy as np
import pytest

from cif2qewan.exceptions import ExternalCommandError, StructureError
from cif2qewan.structure.compare import compare_structures, structures_equivalent
from cif2qewan.structure.model import AtomicSite, MagneticMoment, NormalizedStructure
from cif2qewan.structure.readers import (
    Cif2cellReader,
    PymatgenReader,
    StructureReader,
    parse_cif2cell_output,
)
from conftest import EXAMPLES

FE = EXAMPLES / "PSLibrary" / "Fe"
ALAT = 2.86304


# --------------------------------------------------------------------------
# cif2cell output parser
# --------------------------------------------------------------------------


def test_parse_fe_cif2cell_output():
    out = Cif2cellReader.read_output(FE / "cif_scf.in")
    s = out.structure
    assert s.num_sites == 1
    assert s.sites[0].element == "Fe" and s.sites[0].label == "Fe"
    assert s.sites[0].frac_coords == (0.0, 0.0, 0.0)
    assert s.volume == pytest.approx(ALAT**3 / 2.0)
    assert out.alat == pytest.approx(ALAT)
    assert np.array(out.cell_alat) == pytest.approx(
        np.array([[-0.5, 0.5, 0.5], [0.5, -0.5, 0.5], [0.5, 0.5, -0.5]])
    )
    assert list(out.masses) == ["Fe"]
    assert out.masses["Fe"] == pytest.approx(55.845)
    assert out.kmesh == (21, 21, 21)
    assert "Generated by cif2cell" in out.text


def test_parse_rejects_unusable_output():
    with pytest.raises(StructureError, match="nat/ntyp"):
        parse_cif2cell_output("&SYSTEM\n  ibrav = 0\n/\n")
    text = (FE / "cif_scf.in").read_text()
    with pytest.raises(StructureError, match="ibrav"):
        parse_cif2cell_output(text.replace("ibrav = 0", "ibrav = 3"))
    with pytest.raises(StructureError, match="cannot parse cif2cell output"):
        parse_cif2cell_output(text.replace("ibrav = 0", "ibrav = invalid"))
    with pytest.raises(StructureError, match="ATOMIC_SPECIES"):
        parse_cif2cell_output(
            text.replace("Fe   0.000000000000000", "Co   0.000000000000000")
        )
    with pytest.raises(StructureError, match="nat = 1"):
        parse_cif2cell_output(
            text.replace(
                "Fe   0.000000000000000   0.000000000000000   0.000000000000000 \n",
                "Fe   0.0 0.0 0.0\nFe   0.5 0.5 0.5\n",
            )
        )


def test_parse_accepts_angstrom_and_bohr_cells():
    text = textwrap.dedent("""
        &SYSTEM
          ibrav = 0
          nat = 1
          ntyp = 1
        /
        CELL_PARAMETERS {angstrom}
          4.0 0.0 0.0
          0.0 4.0 0.0
          0.0 0.0 4.0
        ATOMIC_SPECIES
          Na 22.99 Na_PSEUDO
        ATOMIC_POSITIONS {crystal}
        Na 0.0 0.0 0.0
        """)
    out = parse_cif2cell_output(text)
    assert out.structure.volume == pytest.approx(64.0)
    assert out.alat == pytest.approx(4.0)
    assert out.kmesh is None

    bohr = text.replace("{angstrom}", "{bohr}")
    assert parse_cif2cell_output(bohr).structure.volume == pytest.approx(
        64.0 * 0.529177210903**3
    )


def test_read_output_requires_an_existing_file(tmp_path):
    with pytest.raises(StructureError, match="not found"):
        Cif2cellReader.read_output(tmp_path / "missing.in")


